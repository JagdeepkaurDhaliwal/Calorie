def generate_personalized_plan(db: Session, user: User, payload: PersonalizedPlanRequest) -> AIPlanResponse:
    """
    Mode 2: Personalized Plan Generator.
    Calculates BMR & TDEE, structures workouts around user's preferred body parts,
    and tailors calorie & macro balance to the user's specific fitness goal.
    """
    # 1. Biometric calculations
    weight = float(user.weight_kg or 70.0)
    height = float(user.height_cm or 175.0)
    age = int(user.age or 28)
    gender = (user.gender or "male").lower()

    # Mifflin-St Jeor Equation for BMR
    if gender == "female":
        bmr = (10.0 * weight) + (6.25 * height) - (5.0 * age) - 161.0
    else:
        bmr = (10.0 * weight) + (6.25 * height) - (5.0 * age) + 5.0

    # Activity factor based on workout days
    act_multiplier = 1.2 + (payload.workout_days_per_week * 0.05)
    tdee = bmr * act_multiplier

    # Calorie target adjustment based on goal
    goal = payload.goal.lower()
    if "loss" in goal or "fat" in goal:
        target_calories = round(tdee - 450.0, -1)
        macro_split = {"protein_pct": 35, "carbs_pct": 40, "fat_pct": 25}
    elif "muscle" in goal or "gain" in goal:
        target_calories = round(tdee + 350.0, -1)
        macro_split = {"protein_pct": 30, "carbs_pct": 50, "fat_pct": 20}
    else:
        target_calories = round(tdee, -1)
        macro_split = {"protein_pct": 25, "carbs_pct": 50, "fat_pct": 25}

    if payload.target_calories and payload.target_calories > 800:
        target_calories = payload.target_calories

    # Save preference update to user
    user.fitness_goal = payload.goal
    user.daily_calorie_target = target_calories
    if payload.preferred_body_parts:
        user.preferred_body_parts = ",".join(payload.preferred_body_parts)
    if payload.dietary_preference:
        user.dietary_preference = payload.dietary_preference
    db.commit()

    # 2. Build personalized workout split matching target body parts
    body_parts = payload.preferred_body_parts or ["chest", "back", "legs", "shoulders", "biceps", "triceps"]
    schedule = []
    days = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]

    bp_index = 0
    workout_days_count = min(max(payload.workout_days_per_week, 2), 6)

    for i, day in enumerate(days):
        if i < workout_days_count:
            bp1 = body_parts[bp_index % len(body_parts)].capitalize()
            bp2 = body_parts[(bp_index + 1) % len(body_parts)].capitalize() if len(body_parts) > 1 else "Cardio"
            bp_index += 2
            schedule.append({
                "day": day,
                "focus": f"{bp1} & {bp2}",
                "body_parts": [bp1.lower(), bp2.lower()],
                "target_sets": "12-16 total sets",
                "duration_min": 50,
                "notes": f"Prioritize hypertrophy & strict form on {bp1}.",
            })
        else:
            schedule.append({
                "day": day,
                "focus": "Active Recovery & Mobility",
                "body_parts": ["full_body"],
                "target_sets": "None",
                "duration_min": 25,
                "notes": "Low-intensity walking, stretching, and muscle restoration.",
            })

    workout_plan = {
        "goal": payload.goal,
        "weekly_frequency": f"{workout_days_count} days / week",
        "target_body_parts": body_parts,
        "schedule": schedule,
        "progressive_overload_rule": "Increase resistance by 2.5-5% whenever you can complete top reps with pristine form.",
    }

    nutrition_plan = {
        "daily_target_calories": target_calories,
        "estimated_tdee": round(tdee, 1),
        "estimated_bmr": round(bmr, 1),
        "dietary_preference": payload.dietary_preference,
        "macro_distribution": macro_split,
        "daily_protein_target_grams": round((target_calories * (macro_split["protein_pct"] / 100.0)) / 4.0, 1),
        "daily_carbs_target_grams": round((target_calories * (macro_split["carbs_pct"] / 100.0)) / 4.0, 1),
        "daily_fat_target_grams": round((target_calories * (macro_split["fat_pct"] / 100.0)) / 9.0, 1),
        "disclaimer": DISCLAIMER_TEXT,
    }

    plan = AIPlan(
        user_id=user.id,
        plan_type="personalized",
        goal=payload.goal,
        title=f"Personalized {payload.goal.replace('_', ' ').title()} Blueprint",
        summary=f"Custom-tailored fitness protocol targeting {', '.join(body_parts)} with a goal-calibrated intake of {target_calories:.0f} kcal/day.",
        workout_plan_json=json.dumps(workout_plan),
        nutrition_plan_json=json.dumps(nutrition_plan),
        daily_calorie_target=target_calories,
        is_active=True,
        created_at=datetime.now(UTC).replace(tzinfo=None),
    )
    db.add(plan)
    db.commit()
    db.refresh(plan)

    return AIPlanResponse(
        id=plan.id,
        plan_type=plan.plan_type,
        goal=plan.goal,
        title=plan.title,
        summary=plan.summary,
        workout_plan=workout_plan,
        nutrition_plan=nutrition_plan,
        daily_calorie_target=plan.daily_calorie_target,
        created_at=plan.created_at,
    )


