        reply = (
            "For optimal hypertrophy and calorie burn, select your target muscle on the **Interactive Body Map**. "
            "Highlighting any body part in red lets you log exercises with exact sets, reps, and resistance. "
            "CalorieCast automatically calculates mechanical work volume and physiological burn rate."
        )
        actions = ["Open Body Map", "Log Exercise", "Start Live Workout"]

