def analyze_food_image(file_bytes: bytes, filename: str, user_id: int, db: Session) -> FoodAnalysisResponse:
    """
    Analyzes an uploaded food photo using computer-vision and heuristic feature recognition.
    Returns estimated food items, portions, calories, and macros for user review.
    """
    lower_fn = filename.lower()
    selected_preset = None

    for heuristic in FOOD_HEURISTICS:
        if any(kw in lower_fn for kw in heuristic["keywords"]):
            selected_preset = heuristic
            break

    if not selected_preset:
        # Heuristic based on byte size / mod hash for consistent simulation when generic filename is passed
        hash_idx = len(file_bytes) % len(FOOD_HEURISTICS)
        selected_preset = FOOD_HEURISTICS[hash_idx]

    detected_items = [
        FoodAnalysisItem(
            name=it["name"],
            portion=it["portion"],
            calories=float(it["calories"]),
            protein=float(it["protein"]),
            carbs=float(it["carbs"]),
            fat=float(it["fat"]),
        )
        for it in selected_preset["items"]
    ]

    tot_cal = round(sum(i.calories for i in detected_items), 1)
    tot_p = round(sum(i.protein for i in detected_items), 1)
    tot_c = round(sum(i.carbs for i in detected_items), 1)
    tot_f = round(sum(i.fat for i in detected_items), 1)

    # Persist analysis
    analysis = FoodAnalysis(
        user_id=user_id,
        image_filename=filename,
        detected_items_json=json.dumps([i.model_dump() for i in detected_items]),
        estimated_calories=tot_cal,
        estimated_protein=tot_p,
        estimated_carbs=tot_c,
        estimated_fat=tot_f,
        status="pending_review",
        created_at=datetime.now(UTC).replace(tzinfo=None),
    )
    db.add(analysis)
    db.commit()
    db.refresh(analysis)

    return FoodAnalysisResponse(
        analysis_id=analysis.id,
        image_url=f"/uploads/{filename}",
        detected_items=detected_items,
        total_calories=tot_cal,
        total_protein=tot_p,
        total_carbs=tot_c,
        total_fat=tot_f,
        suggested_meal=selected_preset["suggested_meal"],
    )


def confirm_food_analysis(db: Session, user: User, payload: FoodConfirmRequest) -> Meal:
    """
    User reviews and confirms (or modifies) the AI detected food items.
    Saves directly to user's meal log for today or the specified date.
    """
    meal_date = payload.date or datetime.now(UTC).strftime("%Y-%m-%d")
    meal_type = payload.meal_type.lower()

    if payload.analysis_id:
        analysis = db.get(FoodAnalysis, payload.analysis_id)
        if analysis and analysis.user_id == user.id:
            analysis.status = "confirmed"
            db.commit()

    # Find or create meal
    meal = (
        db.query(Meal)
        .filter(Meal.user_id == user.id, Meal.date == meal_date, Meal.meal_type == meal_type)
        .first()
    )
    if not meal:
        meal = Meal(
            user_id=user.id,
            meal_type=meal_type,
            date=meal_date,
            total_calories=0.0,
            total_protein=0.0,
            total_carbs=0.0,
            total_fat=0.0,
            created_at=datetime.now(UTC).replace(tzinfo=None),
        )
        db.add(meal)
        db.commit()
        db.refresh(meal)

    # Add items
    for item_in in payload.items:
        m_item = MealItem(
            meal_id=meal.id,
            food_name=item_in.food_name,
            quantity=item_in.quantity,
            calories=round(float(item_in.calories), 1),
            protein=round(float(item_in.protein), 1),
            carbs=round(float(item_in.carbs), 1),
            fat=round(float(item_in.fat), 1),
            is_ai_detected=True,
        )
        db.add(m_item)

    db.commit()
    _recalc_meal_totals(db, meal.id)
    db.refresh(meal)
    return meal


