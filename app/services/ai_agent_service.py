            "1. **Mode 1: General Maintenance Plan** – A balanced 7-day routine covering all muscle groups and cardio.\n"
            "2. **Mode 2: Personalized Blueprint** – Tailored to your target muscles, BMR/TDEE, and fitness goals.\n\n"
            "Head to the **AI Fitness Agent** tab to generate your plan!"
